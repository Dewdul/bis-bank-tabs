#!/usr/bin/env python3
"""Turn a verified unique-use research run (JSON: {"items": [...]}) into
tools/unique_uses.py, the reviewed data curated.py merges into the tabs.

Each research item: page, tab, group, groupLabel, groupMode (best|all), rank,
slot, reason, category. Groups whose items span several equipment slots become
sets (one piece per slot) so the layout keeps them in one alternatives column.

Usage: python tools/import_unique.py research.json [more.json ...]
"""
import json
import sys
from collections import OrderedDict
from pathlib import Path

OUT = Path(__file__).resolve().parent / "unique_uses.py"


def main(paths):
    items = []
    for p in paths:
        items += json.loads(Path(p).read_text(encoding="utf-8"))["items"]
    groups = OrderedDict()
    for it in sorted(items, key=lambda x: (x["tab"], x["group"], x["rank"])):
        groups.setdefault((it["tab"], it["group"]), []).append(it)

    out, seen_sets = [], set()
    for (tab, key), members in groups.items():
        pages, entries = [], []
        for m in members:
            if m["page"] not in pages:
                pages.append(m["page"])
                entries.append(m)
        # the same items under two group names (e.g. "antidragon" and "antifire_shield_melee"): keep the first
        signature = (tab, frozenset(pages))
        if signature in seen_sets:
            continue
        seen_sets.add(signature)
        first = entries[0]
        group = {"tab": tab, "group": key, "label": first["groupLabel"],
                 "mode": "best" if all(m["groupMode"] == "best" for m in entries) else "all",
                 "special": first.get("category") == "specials" or key.startswith("spec")}
        slots = [m["slot"] for m in entries if m["slot"]]
        if len(set(slots)) > 1:
            pieces = OrderedDict()
            for m in entries:
                pieces.setdefault(m["slot"] or "WEAPON", []).append([m["page"], m["reason"]])
            group["pieces"] = [{"slot": s, "items": v} for s, v in pieces.items()]
        else:
            group["slot"] = slots[0] if slots else None
            group["items"] = [[m["page"], m["reason"]] for m in entries]
        out.append(group)

    lines = ['"""Wiki-verified unique-use items, generated by tools/import_unique.py from a research run.',
             "", "Edit freely: curated.apply_unique merges these into the tabs.", '"""', "", "UNIQUE_USES = ["]
    for g in out:
        lines.append("    " + json.dumps(g, ensure_ascii=False) + ",")
    lines.append("]")
    OUT.write_text("\n".join(lines).replace(": null", ": None").replace(": true", ": True")
                   .replace(": false", ": False") + "\n", encoding="utf-8")
    print("wrote %s: %d groups from %d items" % (OUT, len(out), len(items)))


if __name__ == "__main__":
    main(sys.argv[1:])
